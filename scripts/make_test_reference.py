"""Generate docs/statistical_tests.md from the code catalogue.

The documentation is derived from ``ds_agent/stats/tests.py`` and
``ds_agent/stats/panels.py`` so a test can never exist in the agent and be
missing from the reference (and vice versa). Run from the repo root:

    python scripts/make_test_reference.py

``tests/test_stats.py`` asserts the generated file contains every catalogue entry.
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List

from ds_agent.stats import panels
from ds_agent.stats import tests as T

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "statistical_tests.md"


def _panel_rows() -> List[str]:
    lines = ["| Readout | Tests reported | Why these |", "| --- | --- | --- |"]
    for spec in panels.PANEL_SPEC.values():
        names = []
        for key in spec["tests"]:
            for part in key.split("|"):
                meta = T.describe(part)
                if meta:
                    names.append(f"{meta['name_zh']} / {meta['name_en']}")
        lines.append(
            f"| {spec['name_zh']} / {spec['name_en']} | {'<br>'.join(names)} | {spec['why_zh']}<br>{spec['why_en']} |"
        )
    return lines


def _entries() -> List[str]:
    lines: List[str] = []
    current_family = ""
    for entry in T.catalogue():
        family = entry["family_zh"]
        if family != current_family:
            current_family = family
            lines += ["", f"### {family} · {entry['family_en']}", ""]
        lines += [
            f"#### {entry['name_zh']} / {entry['name_en']}",
            "",
            f"- **原假设 / H0**: {entry['h0_zh']} / {entry['h0_en']}",
            f"- **统计量 / Statistic**: `{entry['formula']}`",
            f"- **前提 / Assumptions**: {entry['assume_zh']} / {entry['assume_en']}",
            f"- **适用 / When to use**: {entry['use_zh']} / {entry['use_en']}",
            f"- **判定 / Decision**: p < α → {entry['reject_zh']} / {entry['reject_en']}; "
            f"otherwise → {entry['retain_zh']} / {entry['retain_en']}",
            f"- **参考 / Reference**: {entry['ref']}（{entry['short_ref']}）",
            "",
        ]
    return lines


def render() -> str:
    header = [
        "# Statistical tests: theory reference and decision rules",
        "",
        "> Generated by `scripts/make_test_reference.py` from `ds_agent/stats/tests.py` and "
        "`ds_agent/stats/panels.py`. Do not edit by hand — edit the catalogue and re-run the script.",
        "",
        "Every analysis conclusion in this agent carries a table of the tests it ran, each row with "
        "the statistic, the p-value, the decision and the citation. This document is the theory behind "
        "those rows: what the null hypothesis is, why the statistic has the form it has, which "
        "assumptions must hold, and where the method comes from.",
        "",
        "## 1. How to read a test result",
        "",
        "| Concept | Meaning | Common mistake |",
        "| --- | --- | --- |",
        "| H0 | The default claim: no difference, no effect, no association, the series is stationary | Stating H0 after seeing the data |",
        "| p-value | P(data at least this extreme \\| H0 is true) | Reading it as P(H0 is true) |",
        "| α | The false-positive rate you accept before looking | Changing α after seeing p |",
        "| Decision | p < α → reject H0; p ≥ α → fail to reject (never \"accept\") | Treating non-significance as proof of no effect |",
        "| Power | 1 − β: the chance of detecting a real effect of a given size | Running an underpowered test and reading the null as a finding |",
        "| Effect size | How large the difference is, in metric units or standardised | Reporting \"significant\" for an effect too small to act on |",
        "| Multiple testing | Many tests inflate false positives; BH-FDR controls the share | Reading 20 raw p-values and shipping the smallest |",
        "| Equivalence | \"No meaningful difference\" requires TOST, not a failed test | Turning p = 0.21 into \"no impact\" |",
        "",
        "## 2. Which tests each readout reports",
        "",
        * _panel_rows(),
        "",
        "The panels are deliberately different: an anomaly readout asks whether a window is below its "
        "seasonal baseline (paired tests), an experiment readout asks whether two independent arms differ "
        "(two-sample tests) and cross-checks it by randomisation. Running every test everywhere would be "
        "noise; running one everywhere would be a claim without support.",
        "",
        f"## 3. The catalogue ({len(T.catalogue())} tests)",
        "",
        "Grouped by the question they answer. Formulas use standard notation: `x̄` mean, `s²` sample "
        "variance, `n` sample size, `Φ` the normal CDF, `r_k` the lag-k autocorrelation.",
    ]
    return "\n".join(header + _entries() + [
        "",
        "## 4. Choosing between competing tests",
        "",
        "| Situation | First choice | Cross-check | Why |",
        "| --- | --- | --- | --- |",
        "| Two independent arms, continuous metric | Welch t | Mann-Whitney + bootstrap | Welch does not assume equal variances; the rank test survives heavy tails |",
        "| Two independent arms, 0/1 metric | Two-proportion z | Chi-square + Fisher (sparse) | Same estimand, three approximations; agreement is evidence |",
        "| Paired before/after | Paired t | Wilcoxon signed-rank | Pairing removes the between-unit variance |",
        "| Three or more arms | One-way ANOVA | Kruskal-Wallis | Omnibus first, then pairwise with BH |",
        "| Normality of residuals | Shapiro-Wilk (n ≤ 5,000) | Jarque-Bera + Anderson-Darling | Each is sensitive to a different departure |",
        "| Equal variances | Levene / Brown-Forsythe | Bartlett (normal data only) | Levene is robust; Bartlett is more powerful but fragile |",
        "| Stationarity | ADF | KPSS | Opposite nulls; agreement is much stronger than either alone |",
        "| Autocorrelation | Ljung-Box | Durbin-Watson | Ljung-Box covers several lags, DW only the first |",
        "| Heteroskedasticity | Breusch-Pagan | White / HC3 SEs | The fix matters more than the test: use robust SEs |",
        "| Model calibration | Hosmer-Lemeshow | Reliability curve | Ranking can be fine while probabilities are wrong |",
        "| \"No difference\" claim | TOST | Equivalence bound from the business | A failed test is not evidence of equivalence |",
        "",
        "## 5. References",
        "",
        "Each entry above carries its own citation; the canonical sources used across the agent are:",
        "",
        "- Kohavi, R., Tang, D. & Xu, Y. (2020). *Trustworthy Online Controlled Experiments*. Cambridge University Press.",
        "- Imbens, G. & Rubin, D. (2015). *Causal Inference for Statistics, Social, and Biomedical Sciences*. Cambridge University Press.",
        "- Hyndman, R. J. & Athanasopoulos, G. (2021). *Forecasting: Principles and Practice* (3rd ed.).",
        "- Efron, B. & Tibshirani, R. (1993). *An Introduction to the Bootstrap*. Chapman & Hall.",
        "- Benjamini, Y. & Hochberg, Y. (1995). Controlling the false discovery rate. *JRSS B* 57(1), 289-300.",
        "",
    ])


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT} ({len(T.catalogue())} tests, {len(panels.PANEL_SPEC)} readouts)")


if __name__ == "__main__":
    main()
