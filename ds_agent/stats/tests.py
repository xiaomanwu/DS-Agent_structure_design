def _clean(x: Any) -> np.ndarray:
    arr = np.asarray(x, dtype=float).ravel()
    return arr[np.isfinite(arr)]


def _result(
    key: str,
    statistic: Optional[float] = None,
    p_value: Optional[float] = None,
    *,
    df: Optional[float] = None,
    n: Optional[int] = None,
    alpha: float = 0.05,
    note_zh: str = "",
    note_en: str = "",
    extra: Optional[Dict[str, Any]] = None,
    p_approx: bool = False,
) -> Dict[str, Any]:
    """Assemble one result row from the catalogue metadata."""
    meta = _META[key]
    out: Dict[str, Any] = {
        "key": key,
        "name_zh": meta["name_zh"],
        "name_en": meta["name_en"],
        "family_zh": meta["family_zh"],
        "family_en": meta["family_en"],
        "h0_zh": meta["h0_zh"],
        "h0_en": meta["h0_en"],
        "stat_name": meta["stat_name"],
        "formula": meta["formula"],
        "assumption_zh": meta["assume_zh"],
        "assumption_en": meta["assume_en"],
        "use_zh": meta["use_zh"],
        "use_en": meta["use_en"],
        "reference": meta["ref"],
        "short_ref": meta["short_ref"],
        "statistic": None if statistic is None else float(statistic),
        "df": None if df is None else float(df),
        "p_value": None if p_value is None else float(p_value),
        "alpha": alpha,
        "n": n,
        "status": "ok",
        "decision": "reject" if (p_value is not None and p_value < alpha) else "retain",
        "significant": bool(p_value < alpha) if p_value is not None else None,
        "p_approx": p_approx,
        "note_zh": note_zh,
        "note_en": note_en,
        "extra": extra or {},
    }
    reject = out["decision"] == "reject"
    out["conclusion_zh"] = meta["reject_zh"] if reject else meta["retain_zh"]
    out["conclusion_en"] = meta["reject_en"] if reject else meta["retain_en"]
    return out


def _skipped(key: str, reason_zh: str, reason_en: str, n: Optional[int] = None) -> Dict[str, Any]:
    """A test that could not run — explicit, never silent."""
    out = _result(key, None, None, n=n)
    out.update(
        {
            "status": "skipped",
            "decision": "skipped",
            "significant": None,
            "conclusion_zh": f"未执行：{reason_zh}",
            "conclusion_en": f"skipped: {reason_en}",
        }
    )
    return out


