def breusch_pagan(resid: Sequence[float], exog: np.ndarray, alpha: float = 0.05) -> Dict[str, Any]:
    e = _clean(resid)
    X = np.asarray(exog, dtype=float)
    if X.ndim == 1:
        X = X.reshape(-1, 1)
    if len(e) != X.shape[0] or len(e) < 10:
        return _skipped("breusch_pagan", "残差与设计矩阵不匹配或样本过小", "residual/exog mismatch or too few rows", len(e))
    e2 = e**2
    X1 = np.column_stack([np.ones(len(e)), X]) if not np.allclose(X[:, 0], 1) else X
    beta, *_ = np.linalg.lstsq(X1, e2, rcond=None)
    fitted = X1 @ beta
    ss_res = float(((e2 - fitted) ** 2).sum())
    ss_tot = float(((e2 - e2.mean()) ** 2).sum())
    r2 = 1 - ss_res / ss_tot if ss_tot > 0 else 0.0
    lm = float(len(e) * r2)
    df = max(X1.shape[1] - 1, 1)
    p = float(stats.chi2.sf(lm, df=df))
    return _result("breusch_pagan", lm, p, df=df, n=len(e), alpha=alpha, extra={"r2": r2})


def variance_inflation(exog: np.ndarray, names: Optional[Sequence[str]] = None) -> Dict[str, Any]:
    """VIF per column; the reported statistic is the maximum, details in ``extra``."""
    X = np.asarray(exog, dtype=float)
    if X.ndim != 2 or X.shape[1] < 2 or X.shape[0] < 10:
        return _skipped("variance_inflation", "解释变量少于 2 个或样本过小", "fewer than 2 regressors or too few rows")
    cols = list(names or [f"x{i}" for i in range(X.shape[1])])
    values: List[Tuple[str, float]] = []
    for j in range(X.shape[1]):
        y = X[:, j]
        others = np.delete(X, j, axis=1)
        others = np.column_stack([np.ones(len(y)), others])
        beta, *_ = np.linalg.lstsq(others, y, rcond=None)
        pred = others @ beta
        ss_res = float(((y - pred) ** 2).sum())
        ss_tot = float(((y - y.mean()) ** 2).sum())
        r2 = 1 - ss_res / ss_tot if ss_tot > 0 else 0.0
        vif = 1 / max(1 - r2, 1e-9)
        values.append((cols[j], float(vif)))
    worst = max(values, key=lambda kv: kv[1])
    out = _result(
        "variance_inflation", worst[1], None, n=X.shape[0],
        note_zh="VIF 无 p 值；|VIF|>10 视为强共线性",
        note_en="VIF has no p-value; > 10 is treated as strong collinearity",
        extra={"vif": values, "worst": worst[0]},
    )
    out["decision"] = "reject" if worst[1] > 10 else "retain"
    out["significant"] = worst[1] > 10
    out["p_value"] = None
    meta = _META["variance_inflation"]
    out["conclusion_zh"] = meta["reject_zh"] if worst[1] > 10 else meta["retain_zh"]
    out["conclusion_en"] = meta["reject_en"] if worst[1] > 10 else meta["retain_en"]
    return out


def hosmer_lemeshow(y_true: Sequence[float], proba: Sequence[float], groups: int = 10, alpha: float = 0.05) -> Dict[str, Any]:
    y_raw = np.asarray(y_true, dtype=float).ravel()
    p_raw = np.asarray(proba, dtype=float).ravel()
    n = min(len(y_raw), len(p_raw))
    y, p_hat = y_raw[:n], p_raw[:n]
    mask = np.isfinite(y) & np.isfinite(p_hat)
    y, p_hat = y[mask], p_hat[mask]
    if len(y) < 50:
        return _skipped("hosmer_lemeshow", "样本不足 50", "fewer than 50 observations", len(y))
    order = np.argsort(p_hat)
    y_sorted, p_sorted = y[order], p_hat[order]
    bins = np.array_split(np.arange(len(y_sorted)), groups)
    chi2 = 0.0
    for idx in bins:
        if len(idx) == 0:
            continue
        obs = float(y_sorted[idx].sum())
        exp = float(p_sorted[idx].sum())
        denom = exp * (1 - exp / len(idx))
        if denom > 0:
            chi2 += (obs - exp) ** 2 / denom
    df = groups - 2
    p = float(stats.chi2.sf(chi2, df=df))
    return _result("hosmer_lemeshow", chi2, p, df=df, n=len(y), alpha=alpha)


