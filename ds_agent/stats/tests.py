def _fmt_p(p: Optional[float]) -> str:
    if p is None or not np.isfinite(p):
        return "-"
    if p < 0.001:
        return "<0.001"
    return f"{p:.4f}"


def _fmt_stat(test: Dict[str, Any]) -> str:
    stat = test.get("statistic")
    if stat is None or not np.isfinite(stat):
        return "-"
    name = test.get("stat_name", "")
    value = f"{stat:,.3f}" if abs(stat) < 1e4 else f"{stat:.3g}"
    return f"{name}={value}" if name else value


def to_frame(tests: Sequence[Dict[str, Any]], lang: str = "zh", include_h0: bool = True) -> pd.DataFrame:
    """One row per test: what ran, the statistic, p, the verdict and the citation."""
    zh = lang != "en"
    rows = []
    for t in tests:
        if t["status"] == "skipped":
            rows.append([t["name_zh"] if zh else t["name_en"], "-", "-", t["conclusion_zh"] if zh else t["conclusion_en"], ""])
            continue
        rows.append(
            [
                t["name_zh"] if zh else t["name_en"],
                _fmt_stat(t),
                _fmt_p(t["p_value"]) + ("*" if t.get("p_approx") else ""),
                t["conclusion_zh"] if zh else t["conclusion_en"],
                t["short_ref"],
            ]
        )
    columns = (
        ["检验", "统计量", "p", "结论", "参考"] if zh else ["test", "statistic", "p", "conclusion", "reference"]
    )
    return pd.DataFrame(rows, columns=columns)


def _p_phrase(p: Optional[float]) -> str:
    """``p<0.001`` or ``p=0.031`` — the form that reads correctly in prose."""
    if p is None or not np.isfinite(p):
        return "p=?"
    return "p<0.001" if p < 0.001 else f"p={p:.4f}"


def summary_line(tests: Sequence[Dict[str, Any]], lang: str = "zh", max_items: int = 6) -> str:
    """One paragraph that names every test that ran and what it concluded.

    This is the sentence that goes into the answer's prose: the table carries the
    detail, the line carries the reasoning.
    """
    zh = lang != "en"
    ran = [t for t in tests if t["status"] == "ok"]
    skipped = [t for t in tests if t["status"] == "skipped"]
    if not ran:
        return "统计检验未执行（样本或数据不足）。" if zh else "No statistical test could run (insufficient data)."
    parts = []
    for t in ran[:max_items]:
        name = t["name_zh"] if zh else t["name_en"]
        parts.append(f"{name}（{_fmt_stat(t)}，{_p_phrase(t['p_value'])}）→ {'拒绝' if t['decision'] == 'reject' else '不拒绝'} H0")
    head = (
        f"本次结论附 {len(ran)} 项检验：" if zh else f"{len(ran)} tests accompany this conclusion: "
    )
    tail = ""
    if skipped:
        tail = (
            f"；另有 {len(skipped)} 项未执行（{skipped[0]['name_zh'] if zh else skipped[0]['name_en']} 等）"
            if zh
            else f"; {len(skipped)} skipped ({skipped[0]['name_en']} etc.)"
        )
    return head + "；".join(parts) + tail + ("。" if zh else ".")


def agreement(tests: Sequence[Dict[str, Any]], keys: Sequence[str]) -> Optional[bool]:
    """Do the named tests agree on rejecting/retaining?"""
    chosen = [t for t in tests if t["key"] in keys and t["status"] == "ok"]
    if len(chosen) < 2:
        return None
    decisions = {t["decision"] for t in chosen}
    return len(decisions) == 1
