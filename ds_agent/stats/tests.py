"""Statistical test battery: every test the agent runs, with its theory attached.

The agent used to quote a single p-value per conclusion. A number like
``p=0.031`` is not a result on its own: it depends on a null hypothesis, a
distributional assumption, and a decision rule, none of which the reader could
see. This module makes the whole chain explicit.

Each test returns one dictionary with a fixed shape:

* ``name_zh`` / ``name_en``  - what was run, in both languages
* ``h0_zh`` / ``h0_en``      - the null hypothesis it actually tests
* ``statistic`` / ``df`` / ``p_value`` / ``alpha`` / ``decision``
* ``conclusion_zh`` / ``conclusion_en`` - the plain-language verdict
* ``assumption_*``, ``formula``, ``reference`` - the theory behind it

``CATALOGUE`` is the single source of truth: the executable functions below and
``docs/statistical_tests.md`` (generated by ``scripts/make_test_reference.py``)
both read from it, so a test cannot exist in the code and be missing from the
documentation.

Design rules that matter:

* **Never raise.** A test that cannot run returns ``status="skipped"`` with a
  reason. A diagnostic that crashes the readout is worse than a missing
  diagnostic.
* **Never fake a p-value.** When an assumption is violated the test still runs
  and the note says what was violated; the caller decides.
* **Deterministic.** Permutation and bootstrap take a seed.
"""

