def anderson_darling(x: Sequence[float], alpha: float = 0.05) -> Dict[str, Any]:
    arr = _clean(x)
    if len(arr) < 8:
        return _skipped("anderson_darling", "样本不足 8 个", "fewer than 8 observations", len(arr))
    try:
        with warnings.catch_warnings():
            # scipy >= 1.17 deprecates the critical-value table; the table is
            # exactly what this approximation needs, so silence the notice.
            warnings.simplefilter("ignore", FutureWarning)
            res = stats.anderson(arr, dist="norm")
    except Exception as exc:  # noqa: BLE001
        return _skipped("anderson_darling", f"计算失败：{exc}", f"computation failed: {exc}", len(arr))
    # scipy reports critical values at 15/10/5/2.5/1%; interpolate p on the log
    # scale between the tabulated points, and label the p as approximate.
    sig = np.asarray(res.significance_level, dtype=float) / 100.0
    crit = np.asarray(res.critical_values, dtype=float)
    order = np.argsort(crit)
    crit, sig = crit[order], sig[order]
    if res.statistic <= crit[0]:
        p = 0.25
    elif res.statistic >= crit[-1]:
        p = 0.005
    else:
        p = float(np.exp(np.interp(res.statistic, crit, np.log(sig))))
    return _result(
        "anderson_darling",
        res.statistic,
        p,
        n=len(arr),
        alpha=alpha,
        p_approx=True,
        note_zh="p 值由临界值表插值近似",
        note_en="p approximated from the critical-value table",
    )


def normality_tests(x: Sequence[float], alpha: float = 0.05) -> List[Dict[str, Any]]:
    """The appropriate normality pair for the sample size, plus Jarque-Bera."""
    arr = _clean(x)
    primary = shapiro_wilk(arr, alpha) if len(arr) <= 5000 else dagostino_k2(arr, alpha)
    return [primary, jarque_bera(arr, alpha), anderson_darling(arr, alpha)]


